import { afterEach, describe, expect, test } from "bun:test";
import { appendFile, mkdir, mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { normalize, promptTitle } from "../src/server/normalize";
import { Recorder } from "../src/server/recorder";
import { removeTestDirectory } from "./helpers";

const cleanup: Array<() => Promise<void>> = [];
afterEach(async () => { for (const close of cleanup.splice(0)) await close(); });

function title(content: unknown, extra: Record<string, unknown> = {}): string {
  return promptTitle(normalize({ type: "user", uuid: "u1", timestamp: "2026-10-17T10:00:00Z", message: { role: "user", content }, ...extra }, "s", 0, 0));
}

// Claude Code records a slash command as its name, message, and arguments, each in its own tag, and a local command's
// output in a record of its own.
const command = (name: string, args: string) => `<command-name>${name}</command-name>\n<command-message>${name.slice(1)}</command-message>\n<command-args>${args}</command-args>`;
const stdout = (text: string) => `<local-command-stdout>${text}</local-command-stdout>`;
const openedFile = "<ide_opened_file>The user opened the file /home/me/app/src/upload.ts in the IDE. This may or may not be related to the current task.</ide_opened_file>";
const selection = "<ide_selection>const retries = 3;</ide_selection>";

describe("session titles", () => {
  // Claude Code's own first-prompt picker, which titles its `--resume` listing, skips every one of these records.
  test("skip the records Claude Code's first-prompt picker skips", () => {
    expect(title(command("/clear", ""))).toBe("");
    expect(title(command("/clear", "  \n "))).toBe("");
    expect(title("<command-name>/compact</command-name>\n<command-message>compact</command-message>")).toBe("");
    expect(title(stdout("Added /home/me/shared as a working directory for this session"))).toBe("");
    expect(title(stdout(""))).toBe("");
    expect(title("<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>")).toBe("");
    expect(title("<session-start-hook>bun install --frozen-lockfile\n106 packages installed</session-start-hook>")).toBe("");
    expect(title("[Request interrupted by user]")).toBe("");
    expect(title("[Request interrupted by user for tool use]")).toBe("");
    expect(title(openedFile)).toBe("");
    expect(title(selection)).toBe("");
    expect(title([{ type: "text", text: openedFile }, { type: "text", text: selection }])).toBe("");
    expect(title("<bash-input></bash-input>")).toBe("");
    expect(title("Summary of the conversation so far", { isCompactSummary: true })).toBe("");
    expect(title("Internal skill instructions", { isMeta: true })).toBe("");
  });

  test("title slash and shell commands the way Claude Code lists them", () => {
    expect(title(command("/review", "PR 12"))).toBe("/review PR 12");
    expect(title(command("/review", "  PR 12\n  and PR 13  "))).toBe("/review PR 12 and PR 13");
    expect(title("<bash-input>bun test</bash-input>")).toBe("! bun test");
    expect(title("<bash-input>\u001b[1mbun\u001b[22m test tests/titles.test.ts</bash-input>")).toBe("! bun test tests/titles.test.ts");
  });

  test("title a prompt by its own words once the context Claude Code attached is removed", () => {
    expect(title(`${openedFile}\nWhy does the upload client hang?`)).toBe("Why does the upload client hang?");
    expect(title([{ type: "text", text: selection }, { type: "text", text: "Explain this constant" }])).toBe("Explain this constant");
    expect(title("<system-reminder>Follow CLAUDE.md</system-reminder>Add retries to the upload client")).toBe("Add retries to the upload client");
    // A command or output quoted inside a prompt is prose: only a record that starts with the tag is the command itself.
    expect(title("What does <command-name>/add-dir</command-name> do?")).toBe("What does /add-dir do?");
    expect(title(`Explain ${stdout("Added /home/me/shared as a working directory")}`)).toBe("Explain Added /home/me/shared as a working directory");
    expect(title("x".repeat(200))).toHaveLength(180);
  });

  test("a recording takes its title from the first record the rules title, however many skipped records come first", async () => {
    const root = await mkdtemp(join(tmpdir(), "blackbox-titles-"));
    const data = join(root, "claude"), folder = join(data, "projects", "app");
    await mkdir(folder, { recursive: true });
    let recorder: Recorder | undefined;
    cleanup.push(async () => { await recorder?.close(); await removeTestDirectory(root); });
    const record = (session: string, uuid: string, parentUuid: string | null, content: string) => JSON.stringify({
      type: "user", uuid, parentUuid, timestamp: "2026-10-17T10:00:00Z", cwd: "/home/me/app", sessionId: session, message: { role: "user", content },
    }) + "\n";
    // The two recordings the issue reproduces with, then a shell command, then a recording that holds only a command.
    await writeFile(join(folder, "s2.jsonl"), record("s2", "b1", null, command("/clear", "")) + record("s2", "b2", "b1", stdout("")) + record("s2", "b3", "b2", "Add retries to the upload client"));
    await writeFile(join(folder, "s3.jsonl"), record("s3", "c1", null, openedFile) + record("s3", "c2", "c1", "Why does the upload client hang?"));
    await writeFile(join(folder, "s4.jsonl"), record("s4", "d1", null, "<bash-input>bun test</bash-input>") + record("s4", "d2", "d1", "<bash-stdout>186 pass</bash-stdout><bash-stderr></bash-stderr>") + record("s4", "d3", "d2", "Why did one test skip?"));
    await writeFile(join(folder, "s5.jsonl"), record("s5", "e1", null, command("/model", "")));
    recorder = await Recorder.open(data, join(root, "state"));
    const titles = () => new Map(recorder!.list(new URLSearchParams()).items.map(session => [session.sessionId, session.title]));
    expect(titles()).toEqual(new Map([["s2", "Add retries to the upload client"], ["s3", "Why does the upload client hang?"], ["s4", "! bun test"], ["s5", "Session s5"]]));
    // The fallback stays open, so the prompt that arrives later takes over the title on the next scan.
    await appendFile(join(folder, "s5.jsonl"), record("s5", "e2", "e1", stdout("Set model to sonnet")) + record("s5", "e3", "e2", "Switch the upload client to streaming"));
    await recorder.scan();
    expect(titles().get("s5")).toBe("Switch the upload client to streaming");
  });
});
